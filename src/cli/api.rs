/// Attempts [`retry_rate_limited`] makes before giving up on a rate limit.
const PACED_ATTEMPTS: usize = 3;

/// Run an SDK call for a command that sends several requests to the same
/// route (paging, or one request per filter value). The gateway rate-limits
/// these routes to about one call a second per member, so a rate-limited call
/// waits the delay the upstream suggests and is retried, instead of failing
/// the whole command.
pub(crate) async fn retry_rate_limited<T, F, Fut>(verbose: bool, mut call: F) -> Result<T>
where
    F: FnMut() -> Fut,
    Fut: std::future::Future<Output = longbridge::Result<T>>,
{
    let mut attempt = 1;
    loop {
        match call().await.map_err(anyhow::Error::from) {
            Err(err) if attempt < PACED_ATTEMPTS && is_rate_limited(&err) => {
                let delay = backoff_delay(&format!("{err:#}"));
                if verbose {
                    eprintln!("* rate limited, retrying in {}ms", delay.as_millis());
                }
                tokio::time::sleep(delay).await;
                attempt += 1;
            }
            result => return result,
        }
    }
}

/// Whether `err` is a gateway rate-limit rejection: an `OpenAPI` business code
/// in the 429xxx range (429002 "区间调用上限", 429003 "最小间隔"). A bare HTTP
/// 429 is not matched: the SDK's `send()` already retries that itself.
fn is_rate_limited(err: &anyhow::Error) -> bool {
    use longbridge::httpclient::HttpClientError;
    let http_error = err.downcast_ref::<HttpClientError>().or_else(|| {
        match err.downcast_ref::<longbridge::Error>() {
            Some(longbridge::Error::HttpClient(e)) => Some(e),
            _ => None,
        }
    });
    matches!(
        http_error,
        Some(HttpClientError::OpenApi { code, .. }) if (429_000..430_000).contains(code)
    )
}

/// How long to wait before retrying a rate-limited call: the wait the upstream
/// suggests ("请 0.4 秒后重试", "retry after: 1s"), clamped to 200ms..1.5s, or
/// 500ms when it suggests none.
fn backoff_delay(message: &str) -> std::time::Duration {
    fn number_before(text: &str, suffix: &str) -> Option<f64> {
        let head = text[..text.find(suffix)?].trim_end();
        let start = head
            .rfind(|c: char| !(c.is_ascii_digit() || c == '.'))
            .map_or(0, |i| {
                i + head[i..].chars().next().map_or(1, char::len_utf8)
            });
        head[start..].parse().ok()
    }
    fn number_after(text: &str, prefix: &str) -> Option<f64> {
        let tail = text[text.find(prefix)? + prefix.len()..].trim_start();
        let end = tail
            .find(|c: char| !(c.is_ascii_digit() || c == '.'))
            .unwrap_or(tail.len());
        tail[..end].parse().ok()
    }
    number_before(message, "秒后重试")
        .or_else(|| number_before(message, "秒後重試"))
        .or_else(|| number_after(message, "retry after:"))
        .filter(|secs| secs.is_finite() && *secs >= 0.0)
        .map_or(std::time::Duration::from_millis(500), |secs| {
            std::time::Duration::from_secs_f64(secs).clamp(
                std::time::Duration::from_millis(200),
                std::time::Duration::from_millis(1500),
            )
        })
}

/// [`http_get`], but restricting the request to a single data center via the
/// SDK's `dc_restrict` API. Region-limited commands declare their region here; the
/// SDK short-circuits a mismatched session with a unified error.
pub async fn http_get_dc(
    path: &str,
    params: &[(&str, &str)],
    dc_restrict: Option<longbridge::DcRegion>,
    verbose: bool,
) -> Result<serde_json::Value> {
    use longbridge::httpclient::Json;
    use reqwest::Method;

    if verbose {
        let qs = params
            .iter()
            .map(|(k, v)| format!("{k}={v}"))
            .collect::<Vec<_>>()
            .join("&");
        eprintln!("* GET {path}?{qs}");
    }
    let client = crate::openapi::http_client();
    let params: Vec<(&str, &str)> = params.to_vec();
    let mut builder = client.request(Method::GET, path).query_params(params);
    if let Some(region) = dc_restrict {
        builder = builder.dc_restrict(region);
    }
    let resp = builder
        .response::<Json<serde_json::Value>>()
        .send()
        .await
        .map_err(anyhow::Error::from)?;
    let mut v = resp.0;
    super::output::strip_private_fields(&mut v);
    Ok(v)
}

pub async fn http_post(
    path: &str,
    body: serde_json::Value,
    verbose: bool,
) -> Result<serde_json::Value> {
    http_post_dc(path, body, None, verbose).await
}

/// [`http_post`], but restricting the request to a single data center via the
/// SDK's `dc_restrict` API.
pub async fn http_post_dc(
    path: &str,
    body: serde_json::Value,
    dc_restrict: Option<longbridge::DcRegion>,
    verbose: bool,
) -> Result<serde_json::Value> {
    use longbridge::httpclient::Json;
    use reqwest::Method;

    if verbose {
        eprintln!("* POST {path}");
        eprintln!(
            "* Body: {}",
            serde_json::to_string_pretty(&body).unwrap_or_default()
        );
    }
    let client = crate::openapi::http_client();
    let mut builder = client.request(Method::POST, path).body(Json(body));
    if let Some(region) = dc_restrict {
        builder = builder.dc_restrict(region);
    }
    let resp = builder
        .response::<Json<serde_json::Value>>()
        .send()
        .await
        .map_err(anyhow::Error::from)?;
    let mut v = resp.0;
    super::output::strip_private_fields(&mut v);
    Ok(v)
}

